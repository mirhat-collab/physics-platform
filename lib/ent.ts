export function sectionNames(subject: EntSubject): string[] {
  return ENT_SUBJECTS[subject].sections.map(s => s.name)
}

export function topicsOf(subject: EntSubject, section: string): string[] {
  return ENT_SUBJECTS[subject].sections.find(s => s.name === section)?.topics ?? []
}

// Раздел, к которому относится тема
export function sectionOfTopic(subject: EntSubject, topic: string): string | undefined {
  return ENT_SUBJECTS[subject].sections.find(s => s.topics.includes(topic))?.name
}

