// ---------- Разбор мини-разметки ----------

export type Tok =
  | { t: 'text'; v: string }
  | { t: 'var'; v: string; slot: number }
  | { t: 'frac'; num: Tok[]; den: Tok[] }
  | { t: 'sqrt'; body: Tok[] }

export function parseFormula(expr: string): { toks: Tok[]; slots: string[] } {
  const slots: string[] = []
  let i = 0

  function parseSeq(stop: string[]): Tok[] {
    const out: Tok[] = []
    let text = ''
    const flush = () => { if (text) { out.push({ t: 'text', v: text }); text = '' } }
    while (i < expr.length && !stop.includes(expr[i])) {
      const ch = expr[i]
      if (ch === '[') {
        flush()
        const end = expr.indexOf(']', i)
        const name = expr.slice(i + 1, end)
        out.push({ t: 'var', v: name, slot: slots.length })
        slots.push(name)
        i = end + 1
      } else if (ch === '{') {
        flush()
        i++
        const num = parseSeq(['|'])
        i++ // |
        const den = parseSeq(['}'])
        i++ // }
        out.push({ t: 'frac', num, den })
      } else if (ch === '√' && expr[i + 1] === '(') {
        flush()
        i += 2
        const body = parseSeq([')'])
        i++ // )
        out.push({ t: 'sqrt', body })
      } else if (ch === '(') {
        // Обычные скобки внутри корня должны быть сбалансированы
        text += ch
        i++
        const inner = parseSeq([')'])
        flush()
        out.push(...inner)
        text += ')'
        i++
      } else {
        text += ch
        i++
      }
    }
    flush()
    return out
  }

  const toks = parseSeq([])
  return { toks, slots }
}

// Все буквы, которые встречаются в разделе — из них берём «ложные» варианты
export function variablePool(subject: Subject): string[] {
  const set = new Set<string>()
  for (const f of FORMULAS) {
    if (f.subject !== subject) continue
    for (const name of parseFormula(f.expr).slots) set.add(name)
  }
  return Array.from(set)
}
