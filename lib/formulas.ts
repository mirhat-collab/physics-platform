// Кроме букв-переменных, в формуле можно прятать «служебные» части:
// названия функций (sin, cos, log…), числа (2, π…) и знаки (+, −, ±).
// Их не нужно размечать — они находятся в тексте формулы автоматически.
export type ConstKind = 'trig' | 'arc' | 'log' | 'num' | 'sign'

export type Tok =
  | { t: 'text'; v: string }
  | { t: 'var'; v: string; slot: number }
  | { t: 'const'; v: string; slot: number; kind: ConstKind }
  | { t: 'frac'; num: Tok[]; den: Tok[] }
  | { t: 'sqrt'; body: Tok[] }

export type Slot = { name: string; kind: 'var' | ConstKind }

const CONST_RE = /arcsin|arccos|arcctg|arctg|sin|cos|ctg|tg|log|lg|ln|π|\d+(?:,\d+)?|[+−±]/g

function constKind(v: string): ConstKind {
  if (/^arc/.test(v)) return 'arc'
  if (/^(sin|cos|tg|ctg)$/.test(v)) return 'trig'
  if (/^(log|lg|ln)$/.test(v)) return 'log'
  if (/^[+−±]$/.test(v)) return 'sign'
  return 'num'
}

export function parseFormula(expr: string): { toks: Tok[]; slots: string[]; kinds: Slot['kind'][] } {
  const slots: string[] = []
  const kinds: Slot['kind'][] = []
  let i = 0

  function pushText(out: Tok[], text: string) {
    let last = 0
    for (const m of text.matchAll(CONST_RE)) {
      if (m.index! > last) out.push({ t: 'text', v: text.slice(last, m.index) })
      const kind = constKind(m[0])
      out.push({ t: 'const', v: m[0], slot: slots.length, kind })
      slots.push(m[0])
      kinds.push(kind)
      last = m.index! + m[0].length
    }
    if (last < text.length) out.push({ t: 'text', v: text.slice(last) })
  }

  function parseSeq(stop: string[]): Tok[] {
    const out: Tok[] = []
    let text = ''
    const flush = () => { if (text) { pushText(out, text); text = '' } }
    while (i < expr.length && !stop.includes(expr[i])) {
      const ch = expr[i]
      if (ch === '[') {
        flush()
        const end = expr.indexOf(']', i)
        const name = expr.slice(i + 1, end)
        out.push({ t: 'var', v: name, slot: slots.length })
        slots.push(name)
        kinds.push('var')
        i = end + 1
      } else if (ch === '{') {
        flush()
        i++
        const num = parseSeq(['|'])
        i++ // |
        const den = parseSeq(['}'])
        i++ // }
        out.push({ t: 'frac', num, den })
      } else if (ch === '√' && expr[i + 1] === '(') {
        flush()
        i += 2
        const body = parseSeq([')'])
        i++ // )
        out.push({ t: 'sqrt', body })
      } else if (ch === '(') {
        // Обычные скобки внутри корня должны быть сбалансированы
        text += ch
        i++
        flush()
        const inner = parseSeq([')'])
        out.push(...inner)
        text += ')'
        i++
      } else {
        text += ch
        i++
      }
    }
    flush()
    return out
  }

  const toks = parseSeq([])
  return { toks, slots, kinds }
}

// Все буквы, функции и числа предмета — из них берём «ложные» варианты
// того же вида: вместо sin предлагаем cos или tg, вместо 2 — другое число.
export function choicePool(subject: Subject): Record<Slot['kind'], string[]> {
  const pool: Record<Slot['kind'], Set<string>> = {
    var: new Set(), trig: new Set(['sin', 'cos', 'tg', 'ctg']), arc: new Set(['arcsin', 'arccos', 'arctg', 'arcctg']),
    log: new Set(['log', 'lg', 'ln']), num: new Set(['1', '2', '3', '4', 'π']), sign: new Set(['+', '−', '±']),
  }
  for (const f of FORMULAS) {
    if (f.subject !== subject) continue
    const { slots, kinds } = parseFormula(f.expr)
    slots.forEach((name, k) => pool[kinds[k]].add(name))
  }
  return Object.fromEntries(Object.entries(pool).map(([k, v]) => [k, Array.from(v)])) as Record<Slot['kind'], string[]>
}
