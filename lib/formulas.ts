// База формул для тренажёра.
//
// Мини-разметка формулы:
//   [x]          — переменная (её можно спрятать и попросить вставить)
//   {числ|знам}  — дробь
//   √(…)         — корень
//   всё остальное — обычный текст (знаки, цифры, степени ², ³)
// Индексы пишем юникодом прямо в имени переменной: [v₀], [Eₖ], [R₁].

export type Subject = 'physics' | 'math'

export type Formula = {
  id: string
  subject: Subject
  section: string
  name: string
  expr: string
  // Расшифровка букв — показываем после ответа
  legend: Record<string, string>
}

type Raw = [name: string, expr: string, legend: Record<string, string>]

function build(subject: Subject, section: string, items: Raw[]): Formula[] {
  return items.map(([name, expr, legend], i) => ({
    id: `${subject}-${section}-${i}`,
    subject, section, name, expr, legend,
  }))
}

