// Столбчатая диаграмма: подписи под столбцами — номера, значения над столбцами
function bars(values: number[]): string {
  const W = 300, H = 190, L = 34, B = 26, T = 14, max = Math.max(...values), top = Math.ceil(max / 10) * 10 || 10
  const bw = (W - L - 10) / values.length
  const y = (v: number) => H - B - ((H - B - T) * v) / top
  let b = ''
  for (let g = 0; g <= top; g += top / 5) {
    b += `<line x1="${L}" y1="${y(g).toFixed(1)}" x2="${W - 6}" y2="${y(g).toFixed(1)}" stroke="currentColor" stroke-opacity="0.15"/>`
    b += `<text x="${L - 5}" y="${(y(g) + 4).toFixed(1)}" text-anchor="end" fill="currentColor">${g}</text>`
  }
  values.forEach((v, i) => {
    const x = L + i * bw + bw * 0.2
    b += `<rect x="${x.toFixed(1)}" y="${y(v).toFixed(1)}" width="${(bw * 0.6).toFixed(1)}" height="${(y(0) - y(v)).toFixed(1)}" fill="var(--accent, #8b7cf6)" fill-opacity="0.75"/>`
    b += `<text x="${(x + bw * 0.3).toFixed(1)}" y="${H - 8}" text-anchor="middle" fill="currentColor" font-weight="700">${i + 1}</text>`
  })
  b += `<line x1="${L}" y1="${y(0)}" x2="${W - 6}" y2="${y(0)}" stroke="currentColor" stroke-width="1.5"/>`
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${W} ${H}" width="100%" style="max-width:${W}px;display:block" font-family="inherit" font-size="12">${b}</svg>`
}
