const pl = (n: number, one: string, few: string, many: string) => {
  if (!Number.isInteger(n)) return few
  const a = Math.abs(n) % 100, b = a % 10
  return a > 10 && a < 20 ? many : b === 1 ? one : b >= 2 && b <= 4 ? few : many
}
