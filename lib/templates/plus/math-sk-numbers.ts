// Отрицательное число в скобках
const pr = (k: number) => (k < 0 ? `(${k})` : `${k}`)
// Многочлен по списку [коэффициент, буквенная часть]
const poly = (terms: [number, string][]) => {
  let s = ''
  for (const [k, v] of terms) {
    if (k === 0) continue
    const a = Math.abs(k), body = v && a === 1 ? v : `${a}${v}`
    s += s ? (k < 0 ? ` - ${body}` : ` + ${body}`) : k < 0 ? `-${body}` : body
  }
  return s || '0'
}
// Комплексное число a + bi
const cx = (re: number, im: number) => {
  if (im === 0) return String(re)
  const t = Math.abs(im) === 1 ? 'i' : `${Math.abs(im)}i`
  if (re === 0) return im < 0 ? `-${t}` : t
  return `${re} ${im < 0 ? '-' : '+'} ${t}`
}
