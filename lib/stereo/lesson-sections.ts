// Урок «Сечения многогранников».
import { C, type Lesson, type SceneLine, type ScenePoint, type V3 } from './types'

const G = C.gray
const edge = (a: V3, b: V3, color: string = G, thin = true): SceneLine => ({ a, b, color, thin })
const lerp = (a: V3, b: V3, t: number): V3 => [a[0] + (b[0] - a[0]) * t, a[1] + (b[1] - a[1]) * t, a[2] + (b[2] - a[2]) * t]
const poly = (ps: V3[], color: string): SceneLine[] => ps.map((p, i) => edge(p, ps[(i + 1) % ps.length], color, false))

// Куб ABCDA₁B₁C₁D₁ с ребром 2
const K: Record<string, V3> = { A: [-1, -1, 1], B: [1, -1, 1], C: [1, -1, -1], D: [-1, -1, -1], A1: [-1, 1, 1], B1: [1, 1, 1], C1: [1, 1, -1], D1: [-1, 1, -1] }
const cube: SceneLine[] = ([['A', 'B'], ['B', 'C'], ['C', 'D'], ['D', 'A'], ['A1', 'B1'], ['B1', 'C1'], ['C1', 'D1'], ['D1', 'A1'], ['A', 'A1'], ['B', 'B1'], ['C', 'C1'], ['D', 'D1']] as const).map(([a, b]) => edge(K[a], K[b]))
const cubePts: ScenePoint[] = Object.entries(K).map(([n, at]) => ({ at, label: n.replace('1', '₁') }))
const mid = (a: string, b: string) => lerp(K[a], K[b], 0.5)

// Сечения куба
const tri = [mid('B1', 'A1'), mid('B1', 'C1'), mid('B1', 'B')]
const hexagon = [mid('A', 'B'), mid('B', 'C'), mid('C', 'C1'), mid('C1', 'D1'), mid('D1', 'A1'), mid('A1', 'A')]
const diag = [K.A, K.C, K.C1, K.A1]
const M = mid('A', 'B'), N = mid('B', 'C'), trap = [K.A1, M, N, K.C1]

// Прямоугольный параллелепипед 5 × 12 × 7 (масштаб 0,2) для задачи
const bx = 0.5, bz = 1.2, by = 0.7
const BX: Record<string, V3> = { A: [-bx, -by, bz], B: [bx, -by, bz], C: [bx, -by, -bz], D: [-bx, -by, -bz], A1: [-bx, by, bz], B1: [bx, by, bz], C1: [bx, by, -bz], D1: [-bx, by, -bz] }
const boxLines: SceneLine[] = ([['A', 'B'], ['B', 'C'], ['C', 'D'], ['D', 'A'], ['A1', 'B1'], ['B1', 'C1'], ['C1', 'D1'], ['D1', 'A1'], ['A', 'A1'], ['B', 'B1'], ['C', 'C1'], ['D', 'D1']] as const).map(([a, b]) => edge(BX[a], BX[b]))
const boxPts: ScenePoint[] = Object.entries(BX).map(([n, at]) => ({ at, label: n.replace('1', '₁') }))
const boxDiag = [BX.A, BX.C, BX.C1, BX.A1]

// Треугольная призма и сечение, параллельное основанию
const TB: V3[] = [[-1.2, -1, 0.8], [1.2, -1, 0.8], [0, -1, -1.2]]
const TT = TB.map(([x, , z]) => [x, 1, z] as V3), TM = TB.map(([x, , z]) => [x, 0.1, z] as V3)
const prism: SceneLine[] = TB.flatMap((p, i) => [edge(p, TB[(i + 1) % 3]), edge(TT[i], TT[(i + 1) % 3]), edge(p, TT[i])])

// Правильная пирамида и сечение на половине высоты
const SQ: V3[] = [[-1.2, -1, 1.2], [1.2, -1, 1.2], [1.2, -1, -1.2], [-1.2, -1, -1.2]]
const S: V3 = [0, 1.4, 0]
const pyr: SceneLine[] = SQ.flatMap((p, i) => [edge(p, SQ[(i + 1) % 4]), edge(S, p)])
const half = SQ.map(p => lerp(S, p, 0.5))

