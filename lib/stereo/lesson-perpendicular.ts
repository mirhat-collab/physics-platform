import { C, type Lesson, type SceneLine, type ScenePlane, type V3 } from './types'

const W = '#e2e8f0'
const add = (a: V3, b: V3): V3 => [a[0] + b[0], a[1] + b[1], a[2] + b[2]]
const subV = (a: V3, b: V3): V3 => [a[0] - b[0], a[1] - b[1], a[2] - b[2]]
const scale = (a: V3, k: number): V3 => [a[0] * k, a[1] * k, a[2] * k]
const norm = (a: V3): V3 => scale(a, 1 / Math.hypot(...a))
const seg = (a: V3, b: V3, color: string, extra: Partial<SceneLine> = {}): SceneLine => ({ a, b, color, ...extra })
// Прямой угол в точке at между направлениями u и w
function right(at: V3, u: V3, w: V3, s = 0.2): SceneLine[] {
  const pu = add(at, scale(norm(u), s)), pw = add(at, scale(norm(w), s)), c = add(pu, scale(norm(w), s))
  return [seg(pu, c, W, { thin: true }), seg(c, pw, W, { thin: true })]
}
// Горизонтальная плоскость y = h
const ground = (h = 0, w = 4.4, d = 3.4, label = 'α'): ScenePlane =>
  ({ corners: [[-w / 2, h, -d / 2], [w / 2, h, -d / 2], [w / 2, h, d / 2], [-w / 2, h, d / 2]], label })

