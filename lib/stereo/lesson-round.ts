const W = '#e2e8f0'
const seg = (a: V3, b: V3, color: string, extra: Partial<SceneLine> = {}): SceneLine => ({ a, b, color, ...extra })
const right = (at: V3, u: V3, w: V3, s = 0.18): SceneLine[] => {
  const n = (v: V3) => { const l = Math.hypot(...v); return v.map(x => (x / l) * s) as V3 }
  const pu: V3 = [at[0] + n(u)[0], at[1] + n(u)[1], at[2] + n(u)[2]], pw: V3 = [at[0] + n(w)[0], at[1] + n(w)[1], at[2] + n(w)[2]]
  const c: V3 = [pu[0] + n(w)[0], pu[1] + n(w)[1], pu[2] + n(w)[2]]
  return [seg(pu, c, W, { thin: true }), seg(c, pw, W, { thin: true })]
}

