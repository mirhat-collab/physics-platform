import { C, type Lesson, type SceneLine, type ScenePlane, type ScenePoint, type V3 } from './types'

const G = C.gray
const add = (a: V3, b: V3): V3 => [a[0] + b[0], a[1] + b[1], a[2] + b[2]]
const sub = (a: V3, b: V3): V3 => [a[0] - b[0], a[1] - b[1], a[2] - b[2]]
const mul = (a: V3, k: number): V3 => [a[0] * k, a[1] * k, a[2] * k]
const unit = (a: V3): V3 => mul(a, 1 / Math.hypot(...a))
const lerp = (a: V3, b: V3, t: number): V3 => add(a, mul(sub(b, a), t))
const seg = (a: V3, b: V3, color: string, extra: Partial<SceneLine> = {}): SceneLine => ({ a, b, color, ...extra })
const edge = (a: V3, b: V3): SceneLine => seg(a, b, G, { thin: true })
const pts = (list: [V3, string][], color?: string): ScenePoint[] => list.map(([at, label]) => ({ at, label, color }))
// Горизонтальная плоскость y = h
const flat = (h: number, label?: string, color: string = C.blue, w = 4.2, d = 3.2): ScenePlane =>
  ({ corners: [[-w / 2, h, -d / 2], [w / 2, h, -d / 2], [w / 2, h, d / 2], [-w / 2, h, d / 2]], label, color })

// Куб ABCDA₁B₁C₁D₁ с ребром 2
const K: Record<string, V3> = { A: [-1, -1, 1], B: [1, -1, 1], C: [1, -1, -1], D: [-1, -1, -1], A1: [-1, 1, 1], B1: [1, 1, 1], C1: [1, 1, -1], D1: [-1, 1, -1] }
const cube: SceneLine[] = ([['A', 'B'], ['B', 'C'], ['C', 'D'], ['D', 'A'], ['A1', 'B1'], ['B1', 'C1'], ['C1', 'D1'], ['D1', 'A1'], ['A', 'A1'], ['B', 'B1'], ['C', 'C1'], ['D', 'D1']] as const).map(([a, b]) => edge(K[a], K[b]))
const cubePts: ScenePoint[] = Object.entries(K).map(([n, at]) => ({ at, label: n.replace('1', '₁') }))

// Скрещивающиеся прямые: b пересекает α в точке M вне прямой a
const M: V3 = [0.6, -0.8, -0.5], bd: V3 = [-0.4, 1.2, 0.6]
const bLow = add(M, mul(bd, -0.6)), bHigh = add(M, mul(bd, 1.3))

// Параллельное проектирование треугольника на плоскость y = −0.9
const dir: V3 = [0.35, -1, 0.25]
const proj = (p: V3): V3 => add(p, mul(dir, (p[1] + 0.9) / 1))
const P: V3 = [-1.1, 1.0, 0.4], Q: V3 = [0.9, 1.3, 0.6], R: V3 = [0.1, 0.6, -0.9]
const P1 = proj(P), Q1 = proj(Q), R1 = proj(R), PQm = lerp(P, Q, 0.5), PQm1 = proj(PQm)

// Задача 2: треугольник ABC, плоскость ∥ AC пересекает AB в M, BC в N (BM : BA = 2 : 5)
const tA: V3 = [-1.6, -0.9, 0.8], tB: V3 = [0, 1.3, 0], tC: V3 = [1.6, -0.9, 0.3]
const tM = lerp(tB, tA, 0.4), tN = lerp(tB, tC, 0.4)
const tu = unit(sub(tC, tA)), tw = unit([0.1, 0.45, -1])
const tPlane: ScenePlane = { corners: [add(add(tM, mul(tu, -0.6)), mul(tw, 1)), add(add(tN, mul(tu, 0.6)), mul(tw, 1)), add(add(tN, mul(tu, 0.6)), mul(tw, -0.9)), add(add(tM, mul(tu, -0.6)), mul(tw, -0.9))], color: C.orange, opacity: 0.18 }

// Задача 3: две прямые из точки O пересекают α в A₁, B₁ и β в A₂, B₂ (OA₁ : OA₂ = 4 : 10)
