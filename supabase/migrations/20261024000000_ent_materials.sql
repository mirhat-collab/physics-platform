-- Справочник ЕНТ: формулы, таблицы, конспекты и файлы, которые загружает
-- администратор. Читать могут все вошедшие, писать — только сервер
-- (через /api/admin/materials под service role после проверки роли admin).
create table if not exists public.ent_materials (
  id bigint generated by default as identity primary key,
  subject text not null default 'general' check (subject in ('physics', 'math', 'general')),
  title text not null,
  body text not null default '',
  media jsonb not null default '[]'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
alter table public.ent_materials enable row level security;
drop policy if exists "ent_materials read" on public.ent_materials;
create policy "ent_materials read" on public.ent_materials
  for select to authenticated using (true);
