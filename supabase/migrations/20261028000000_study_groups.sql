-- Группы учителя: учитель создаёт группу (например, «10А, школа №5»),
-- ученики вступают по ссылке /join/<код> или QR-коду. ДЗ и отчёты можно
-- выдавать только своей группе (homework.class_name = 'group:<id>').

create table if not exists public.study_groups (
  id bigint generated by default as identity primary key,
  teacher_id uuid not null references auth.users(id) on delete cascade,
  name text not null check (char_length(name) between 1 and 80),
  join_code text not null unique,
  created_at timestamptz not null default now()
);

create table if not exists public.study_group_members (
  group_id bigint not null references public.study_groups(id) on delete cascade,
  student_id uuid not null references auth.users(id) on delete cascade,
  joined_at timestamptz not null default now(),
  primary key (group_id, student_id)
);
create index if not exists study_group_members_student_idx on public.study_group_members(student_id);
create index if not exists study_groups_teacher_idx on public.study_groups(teacher_id);

alter table public.study_groups enable row level security;
alter table public.study_group_members enable row level security;

create or replace function public.is_staff()
returns boolean language sql stable security definer set search_path to 'public' as $$
  select exists (select 1 from public.profiles p where p.id = (select auth.uid()) and p.role in ('teacher', 'admin'))
$$;
revoke all on function public.is_staff() from public, anon;
grant execute on function public.is_staff() to authenticated;

-- Проверки для политик — security definer, чтобы политики двух таблиц
-- не ссылались друг на друга (иначе бесконечная рекурсия RLS)
create or replace function public.is_group_member(gid bigint)
returns boolean language sql stable security definer set search_path to 'public' as $$
  select exists (select 1 from public.study_group_members m where m.group_id = gid and m.student_id = (select auth.uid()))
$$;
create or replace function public.is_group_teacher(gid bigint)
returns boolean language sql stable security definer set search_path to 'public' as $$
  select exists (select 1 from public.study_groups g where g.id = gid and g.teacher_id = (select auth.uid()))
$$;
create or replace function public.is_admin()
returns boolean language sql stable security definer set search_path to 'public' as $$
  select exists (select 1 from public.profiles p where p.id = (select auth.uid()) and p.role = 'admin')
$$;
revoke all on function public.is_group_member(bigint) from public, anon;
revoke all on function public.is_group_teacher(bigint) from public, anon;
revoke all on function public.is_admin() from public, anon;
grant execute on function public.is_group_member(bigint) to authenticated;
grant execute on function public.is_group_teacher(bigint) to authenticated;
grant execute on function public.is_admin() to authenticated;

-- Группу видят её учитель, её ученики и админ
drop policy if exists study_groups_select on public.study_groups;
create policy study_groups_select on public.study_groups for select to authenticated using (
  teacher_id = (select auth.uid()) or public.is_group_member(id) or public.is_admin()
);
drop policy if exists study_groups_insert on public.study_groups;
create policy study_groups_insert on public.study_groups for insert to authenticated
  with check (teacher_id = (select auth.uid()) and public.is_staff());
drop policy if exists study_groups_update on public.study_groups;
create policy study_groups_update on public.study_groups for update to authenticated
  using (teacher_id = (select auth.uid())) with check (teacher_id = (select auth.uid()));
drop policy if exists study_groups_delete on public.study_groups;
create policy study_groups_delete on public.study_groups for delete to authenticated
  using (teacher_id = (select auth.uid()));

-- Состав группы видят учитель группы и сам ученик; удалить ученика может
-- учитель, выйти из группы — сам ученик. Вступление — только через join_study_group.
drop policy if exists study_group_members_select on public.study_group_members;
create policy study_group_members_select on public.study_group_members for select to authenticated using (
  student_id = (select auth.uid()) or public.is_group_teacher(group_id) or public.is_admin()
);
drop policy if exists study_group_members_delete on public.study_group_members;
create policy study_group_members_delete on public.study_group_members for delete to authenticated using (
  student_id = (select auth.uid()) or public.is_group_teacher(group_id)
);

-- Вступить в группу по коду: возвращает название группы и имя учителя
create or replace function public.join_study_group(code text)
returns table (group_id bigint, group_name text, teacher_name text)
language plpgsql security definer set search_path to 'public' as $$
#variable_conflict use_column
declare g public.study_groups;
begin
  if (select auth.uid()) is null then raise exception 'not_authenticated'; end if;
  select * into g from public.study_groups where join_code = upper(trim(code));
  if g.id is null then raise exception 'group_not_found'; end if;
  insert into public.study_group_members (group_id, student_id) values (g.id, (select auth.uid()))
    on conflict do nothing;
  return query select g.id, g.name, coalesce(p.full_name, p.email, '') from public.profiles p where p.id = g.teacher_id;
end $$;
revoke all on function public.join_study_group(text) from public, anon;
grant execute on function public.join_study_group(text) to authenticated;

-- Что за группа по коду — до вступления (страница приглашения)
create or replace function public.study_group_by_code(code text)
returns table (group_name text, teacher_name text)
language sql stable security definer set search_path to 'public' as $$
  select g.name, coalesce(p.full_name, '') from public.study_groups g
  left join public.profiles p on p.id = g.teacher_id
  where g.join_code = upper(trim(code))
$$;
revoke all on function public.study_group_by_code(text) from public;
grant execute on function public.study_group_by_code(text) to anon, authenticated;

